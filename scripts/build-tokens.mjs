import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { format } from "prettier";

const INPUT = "tokens/habi.tokens.json";
const OUTPUT = "registry/habi/styles/habi-tokens.css";

const tokens = JSON.parse(await readFile(INPUT, "utf8"));

// "neutral/5" → "neutral-05", "text/primary" → "text-primary", "white" → "white"
function toName(path) {
  return path
    .split("/")
    .map((part) => (/^\d$/.test(part) ? `0${part}` : part))
    .join("-");
}

const px = (n) => `${n}px`;
const rem = (n) => `${n / 16}rem`;

const primitives = [];
for (const [group, value] of Object.entries(tokens.primitive)) {
  if (typeof value === "string") {
    primitives.push([group, value]);
  } else {
    for (const [step, hex] of Object.entries(value)) {
      primitives.push([toName(`${group}/${step}`), hex]);
    }
  }
}
const primitiveNames = new Set(primitives.map(([name]) => name));

// A semantic color is a primitive, or { ref, alpha } for a see-through one.
const semantics = Object.entries(tokens.color).map(([path, value]) => {
  const ref = typeof value === "string" ? value : value.ref;
  const target = toName(ref);
  if (!primitiveNames.has(target)) {
    throw new Error(`"${path}" points to "${ref}", which is not a primitive`);
  }
  const css =
    typeof value === "string"
      ? `var(--${target})`
      : withAlpha(primitives.find(([name]) => name === target)[1], value.alpha);
  return [toName(path), css];
});

// A plain rgb() value, so older browsers don't fall back to the solid colour.
function withAlpha(hex, alpha) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
  return `rgb(${r} ${g} ${b} / ${alpha / 100})`;
}

const colorNames = [...primitives, ...semantics].map(([name]) => name);
const { font, motion } = tokens;

const css = [
  "/* Generated by scripts/build-tokens.mjs from tokens/habi.tokens.json. DO NOT EDIT BY HAND! */",
  "",
  ":root {",
  ...primitives.map(([name, hex]) => `  --${name}: ${hex};`),
  "",
  ...semantics.map(([name, css]) => `  --${name}: ${css};`),
  "",
  `  --font-roundness: ${font.roundness};`,
  "}",
  "",
  "@theme inline {",
  "  --color-*: initial;",
  ...colorNames.map((name) => `  --color-${name}: var(--${name});`),
  "",
  ...Object.entries(tokens.textStyle).flatMap(([name, style]) => [
    `  --text-${name}: ${rem(style.size)};`,
    `  --text-${name}--line-height: ${rem(style.lineHeight)};`,
    `  --text-${name}--font-weight: ${font.weight[style.weight]};`,
  ]),
  "}",
  "",
  "@theme static {",
  `  --font-sans: "${font.sans}", system-ui, sans-serif;`,
  `  --font-mono: ${font.mono};`,
  ...Object.entries(font.weight).map(
    ([name, value]) => `  --font-weight-${name}: ${value};`,
  ),
  ...Object.entries(tokens.radius).map(
    ([name, value]) =>
      `  --radius-${name}: ${typeof value === "string" ? `var(--radius-${value})` : px(value)};`,
  ),
  ...Object.entries(tokens.shadow).map(
    ([name, value]) => `  --shadow-${name}: ${value};`,
  ),
  ...Object.entries(motion.duration).map(
    ([name, ms]) => `  --duration-${name}: ${ms}ms;`,
  ),
  ...Object.entries(motion.easing).map(
    ([name, value]) => `  --ease-${name}: ${value};`,
  ),
  "}",
  "",
  // Theme text sizes can't set a font family, so a utility of the same name adds it.
  ...Object.entries(tokens.textStyle)
    .filter(([, style]) => style.family)
    .flatMap(([name, style]) => [
      `@utility text-${name} {`,
      `  font-family: var(--font-${style.family});`,
      "}",
      "",
    ]),
].join("\n");

await mkdir(dirname(OUTPUT), { recursive: true });
await writeFile(OUTPUT, await format(css, { parser: "css" }));
console.log(
  `Wrote ${OUTPUT} (${primitives.length} primitives, ${semantics.length} semantic colors)`,
);
